export const LAB_TEMPLATE_MAP: Record<string, LabTemplate> = Object.fromEntries(
  LAB_TEMPLATES.map((t) => [t.id, t]),
);

export const CUSTOM_TEMPLATE = "custom";

export function templateFor(kind: string | null | undefined): LabTemplate | null {
  if (!kind) return null;
  return LAB_TEMPLATE_MAP[kind] ?? null;
}

export function kindLabel(kind: string | null | undefined): string {
  if (!kind) return "без типа";
  return LAB_TEMPLATE_MAP[kind]?.label ?? kind;
}

/** Ключ сопоставления показателя из бланка с шаблоном. */
export function rowKey(name: string): string {
  return name.trim().toLowerCase().replace(/\s+/g, " ");
}
