export function codeForName(name: string, panelKind?: string | null): string | null {
  const key = name.trim().toLowerCase().replace(/\s+/g, " ");
  if (panelKind === "urine") {
    const fromUrine = URINE_TO_CODE[key];
    if (fromUrine) return fromUrine;
  }
  return NAME_TO_CODE[key] ?? null;
}

