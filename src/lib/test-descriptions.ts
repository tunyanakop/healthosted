export function infoFor(code: string | null | undefined): TestInfo | null {
  if (!code) return null;
  return TEST_INFO[code] ?? null;
}

/** Текст для всплывающей подсказки: что это + типовые причины отклонений. */
export function tooltipText(code: string | null | undefined): string | null {
  const info = infoFor(code);
  if (!info) return null;

  const parts = [info.what];
  if (info.high) parts.push(`Повышено: ${info.high}.`);
  if (info.low) parts.push(`Понижено: ${info.low}.`);
  if (info.note) parts.push(info.note);
  return parts.join(" ");
}
